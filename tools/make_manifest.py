def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('base', nargs='?', default=BASE, help='HTTPS URL of the folder that serves docs/, ending with a slash')
    ap.add_argument('--id', default=ADDIN_ID, help='"new" for a fresh GUID, or a GUID of your own')
    a = ap.parse_args()
    base = a.base if a.base.endswith('/') else a.base + '/'
    if not base.startswith('https://'):
        sys.exit('Office add-ins must be served over HTTPS.')
    origin = '/'.join(base.split('/')[:3])
    sys.stdout.write(TEMPLATE.format(id=str(uuid.uuid4()) if a.id == 'new' else a.id, version=VERSION, base=base, origin=origin, repo=REPO))


if __name__ == '__main__':
    main()
