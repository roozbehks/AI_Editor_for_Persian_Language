def rule(code, level, pattern, msg, fix=None, strict=False, formal=False):
    RULES.append({'code': code, 'level': level, 're': re.compile(pattern, re.M), 'msg': msg, 'fix': fix,
                  'strict': strict, 'formal': formal})


def words(code, level, mapping, tmpl='«{0}» ← «{1}»', fix=True, mode='exact', strict=False, formal=False):
    """mapping: نادرست -> درست. mode: exact (واژهٔ کامل) · suf (با پسوندهای رایج) · stem (هر دنباله‌ای)."""
    keys = sorted(mapping, key=len, reverse=True)
    tail = {'exact': B1, 'suf': SUF, 'stem': ''}[mode]
    pat = B0 + '(' + '|'.join(re.escape(k) for k in keys) + ')' + tail
    rule(code, level, pat, lambda m: tmpl.format(m.group(1), mapping[m.group(1)]),
         (lambda m: mapping[m.group(1)]) if fix else None, strict, formal)


def ph(code, level, pattern, msg, strict=False, formal=False):
    rule(code, level, pattern, msg, None, strict, formal)


def _join(m):
    """پسوند را به واژهٔ پیش می‌چسباند: پس از حرف جدا بی‌فاصله، وگرنه با نیم‌فاصله."""
    return ('' if m.string[m.start() - 1] in NONJOIN else ZW) + m.group(1)


