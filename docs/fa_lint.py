def selftest():
    bad = 0
    for text, want, unwanted in SELFTEST:
        got = lint(text)
        codes = {f[0] for f in got} | {f[1] for f in got}
        miss = [c for c in want if c not in codes]
        extra = [c for c in unwanted if c in codes]
        if miss or extra:
            bad += 1
            print('✗', text, '| نیامد:', miss, '| نباید می‌آمد:', extra, '|', sorted({f[0] for f in got}))
    print('خودآزمایی: {0} نمونه، {1} ناموفق'.format(len(SELFTEST), bad))
    return 1 if bad else 0


