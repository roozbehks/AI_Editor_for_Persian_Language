def expand(pattern):
    """در الگوهای شیوهٔ خانگی: {B0} {B1} {ZW} {WD} {MI} {LET} {FAD}."""
    for k, v in (('{B0}', B0), ('{B1}', B1), ('{ZW}', ZW), ('{WD}', WD), ('{MI}', MI), ('{LET}', LET), ('{FAD}', FAD)):
        pattern = pattern.replace(k, v)
    return pattern


def _blank(m):
    return re.sub(r'[^\n]', PH, m.group(0))


def mask(text):
    """بخش‌هایی را که نباید وارسی شوند با نویسه‌ای خنثی و هم‌طول می‌پوشاند."""
    text = re.sub(r'\A---\n.*?\n---\n', _blank, text, flags=re.S)  # سرآیند YAML
    text = re.sub(r'```.*?```', _blank, text, flags=re.S)
    text = re.sub(r'<!--\s*fa-lint:off\s*-->.*?(?:<!--\s*fa-lint:on\s*-->|\Z)', _blank, text, flags=re.S)
    text = re.sub(r'`[^`\n]+`', _blank, text)
    text = re.sub(r'https?://\S+|www\.\S+|\S+@\S+\.\S+', _blank, text)
    text = re.sub(r'\]\([^)\n]*\)', _blank, text)
    text = re.sub(r'<[^>\n]{1,200}>', _blank, text)
    return text


def house_rules(cfg):
    out = []

    def add(code, level, pattern, msg, fix=None):
        out.append({'code': code, 'level': level, 're': re.compile(pattern, re.M), 'msg': msg, 'fix': fix,
                    'strict': False, 'formal': False})
    hy = cfg.get('heh_ye', 'هٔ')
    if hy == 'هٔ':
        add('HEH', 'E', 'ۀ', '«ۀ» ← «هٔ» (ه + همزهٔ بالا)', lambda m: 'هٔ')
        add('HEH', 'W', '(?<=[' + LET + '])ه' + ZW + 'ی' + END, '«ه‌ی» ← «هٔ»', lambda m: 'هٔ')
        rep = 'هٔ'
    else:
        add('HEH', 'W', 'هٔ|ۀ', '«هٔ» ← «ه‌ی»', lambda m: 'ه' + ZW + 'ی')
        rep = 'ه' + ZW + 'ی'
    add('HEH', 'E', '(?<=[' + LET + ']{2})ه ی' + END, '«ه ی» با فاصله در هیچ شیوه‌ای درست نیست', lambda m: rep)
    add('HEH', 'W', B0 + '(درباره|به[ ' + ZW + ']وسیله|بر پایه|در زمینه|به گفته|به واسطه|به منزله|به اندازه|در آستانه) (?=[' + LET + '])(?!(?:ام|اش|ات|ای|اند|است|و|که|را|هم|نیز|بود|شد)' + B1 + ')',
        lambda m: 'کسرهٔ اضافه پس از «ه»: «{0}»'.format(m.group(1) + rep[1:]), lambda m: m.group(1) + rep[1:] + ' ')
    add('HEH', 'W', B0 + '(همه) (?=(?:این|آن|ما|شما|آنان|کسانی|آنچه|این' + ZW + 'ها|آن' + ZW + 'ها|اینها|آنها)' + B1 + ')',
        lambda m: 'کسرهٔ اضافه پس از «ه»: «همه{0}»'.format(rep[1:]), lambda m: m.group(1) + rep[1:] + ' ')
    if cfg.get('no_parentheses'):
        add('HOUSE-PAREN', 'W', '(?<![A-Za-z])(?<![A-Za-z] )\\((?![^)\\n]*[A-Za-z])(?![^)\\n]*[' + FAD + '0-9]{4}\\s*\\))(?=[^)\\n]*[' + LET + '])[^)\\n]*\\)',
            'پرانتز در متن روان: توضیح را در خودِ جمله بیاورید (ارجاع و اصطلاح لاتین مستثناست)')
    for bad, good in cfg.get('words', {}).items():
        add('HOUSE', 'W', B0 + re.escape(bad) + SUF, 'شیوهٔ خانگی: «{0}» ← «{1}»'.format(bad, good), lambda m, g=good: g)
    for bad in cfg.get('avoid', []):
        add('HOUSE', 'W', B0 + re.escape(bad) + SUF, 'شیوهٔ خانگی: «{0}» به کار نمی‌رود'.format(bad))
    for item in cfg.get('prefer', []):
        r = item.get('replace')
        add(item.get('code', 'HOUSE'), item.get('level', 'W'), expand(item['pattern']), item.get('say', 'شیوهٔ خانگی'),
            (lambda m, r=r: r) if r is not None else None)
    return out


def number_findings(masked):
    out = []
    skip = ' ([«"\'»)]'
    for m in re.finditer(r'[0-9]+(?:[.,:/][0-9]+)*', masked):
        s, e = m.span()
        before = masked[:s].rstrip(skip)
        after = masked[e:].lstrip(skip)
        pb, pa = before[-1:], after[:1]
        if re.match(r'[A-Za-z_\-#@&=+*^$\\{}<>/]', pb) or re.match(r'[A-Za-z_]', pa):
            continue
        if not (re.match('[' + LET + '،؛؟' + ZW + MARK + ']', pb) or re.match('[' + LET + '٪]', pa)):
            continue
        tok = m.group(0)
        fixed = re.sub(r'(?<=[0-9]),(?=[0-9]{3}(?![0-9]))', '٬', tok).translate(FA_DIGITS)
        out.append(('NUM-LAT', 'W', s, e, 'رقم لاتین در متن فارسی: «{0}» ← «{1}»'.format(tok, fixed), fixed))
    return out


def sentence_findings(masked, cfg, verbless):
    out = []
    max_words = cfg.get('max_sentence_words', 45)
    offset = 0
    for line in masked.split('\n'):
        base, offset = offset, offset + len(line) + 1
        if '|' in line or not re.search('[' + LET + ']', line) or line.lstrip().startswith('#'):
            continue
        for sm in SENT_RE.finditer(line):
            s = sm.group(0)
            if not re.search('[' + LET + ']', s):
                continue
            start = base + sm.start() + (len(s) - len(s.lstrip()))
            pos = 0
            for clause in re.split('[؛:]', s):
                cstart = base + sm.start() + pos + (len(clause) - len(clause.lstrip()))
                pos += len(clause) + 1
                toks = [t for t in (STRIP_TOK.sub('', w) for w in clause.split()) if re.search('[' + LET + ']', t)]
                span = (cstart, cstart + min(len(clause.strip()), 60))
                if len(toks) > max_words:
                    out.append(('SENT-LONG', 'C') + span + ('جملهٔ بلند ({0} واژه بی‌درنگ): بشکنید'.format(len(toks)), None))
                elif clause.count('،') >= 7:
                    out.append(('SENT-COMMA', 'C') + span + ('{0} ویرگول پیاپی: ویرگول‌زدایی کنید یا جمله را بشکنید'.format(clause.count('،')), None))
                if toks.count('که') >= 4:
                    out.append(('SENT-KE', 'C') + span + ('{0} «که» در یک جمله'.format(toks.count('که')), None))
            if verbless and re.search(r'\.["»)\]]*$', s.strip()) and not re.match(r'\s*[^:]{1,30}:', s) and '←' not in s:
                toks = [t for t in (STRIP_TOK.sub('', w) for w in s.split()) if re.search('[' + LET + ']', t)]
                if len(toks) >= 5 and not any(VERB.match(t) for t in toks):
                    out.append(('SENT-NOVERB', 'C', start, start + min(len(s.strip()), 60), 'جملهٔ بی‌فعل؟ (برچسب و عنوان مستثناست)', None))
    return out


def consistency_findings(masked):
    out = []
    for a, b in PAIRS:
        ia = [m.start() for m in re.finditer(B0 + re.escape(a), masked)]
        ib = [m.start() for m in re.finditer(B0 + re.escape(b), masked)]
        if ia and ib:
            minor = b if len(ib) <= len(ia) else a
            first = (ib if minor == b else ia)[0]
            out.append(('CONS', 'C', first, first + len(minor),
                        'ناهمسانی: «{0}» ({1} بار) و «{2}» ({3} بار)؛ یکی را در کل متن نگه دارید'.format(a, len(ia), b, len(ib)), None))
    return out


def lint(text, cfg=None, strict=False, verbless=False, consistency=True):
    """فهرستی از (کد، سطح، آغاز، پایان، پیام، جایگزین یا None) برمی‌گرداند."""
    cfg = cfg or {}
    masked = mask(text)
    for pat in cfg.get('allow', []):
        masked = re.sub(expand(pat), _blank, masked)
    ignore = set(cfg.get('ignore', []))
    formal = cfg.get('formal', True)
    found = []
    for r in RULES + house_rules(cfg):
        if r['code'] in ignore or (r['strict'] and not strict) or (r['formal'] and not formal):
            continue
        for m in r['re'].finditer(masked):
            if m.end() == m.start():
                continue
            msg = r['msg'](m) if callable(r['msg']) else r['msg']
            if msg is None:
                continue
            rep = r['fix'](m) if r['fix'] is not None else None
            if rep is not None and rep == m.group(0):
                continue
            found.append((r['code'], r['level'], m.start(), m.end(), msg, rep))
    if 'NUM-LAT' not in ignore:
        found += number_findings(masked)
    found += [f for f in sentence_findings(masked, cfg, verbless or cfg.get('verbless', False)) if f[0] not in ignore]
    if consistency and 'CONS' not in ignore:
        found += consistency_findings(masked)
    found.sort(key=lambda f: (f[2], 'EWC'.index(f[1]), f[2] - f[3]))
    seen, out = set(), []
    for f in found:
        key = (f[0], f[2], f[3])
        if key in seen:
            continue
        seen.add(key)
        # یافتهٔ ضعیف‌ترِ هم‌کد که درونِ یافته‌ای قوی‌تر افتاده است تکرار است
        if any(g[0] == f[0] and g[2] <= f[2] and f[3] <= g[3] and 'EWC'.index(g[1]) < 'EWC'.index(f[1]) for g in found):
            continue
        out.append(f)
    return out


def apply_fixes(text, findings):
    fixes = sorted(((f[2], f[3], f[5]) for f in findings if f[5] is not None and (f[1] in 'EW' or f[0] in AUTOFIX_C)),
                   key=lambda x: (x[0], -x[1]))
    out, last, n = [], 0, 0
    for s, e, rep in fixes:
        if s < last:
            continue
        out.append(text[last:s])
        out.append(rep)
        last = e
        n += 1
    out.append(text[last:])
    return ''.join(out), n


def fix_text(text, cfg=None, strict=False):
    """متنِ اصلاح‌شده و یافته‌های مانده را برمی‌گرداند."""
    for _ in range(4):
        new, n = apply_fixes(text, lint(text, cfg, strict))
        if not n or new == text:
            break
        text = new
    return text, lint(text, cfg, strict)


def segments_from_file(path):
    """فهرستی از (برچسب، متن، قابل اصلاح) برمی‌گرداند."""
    if path == '-':
        return [('stdin', sys.stdin.read(), True)]
    ext = os.path.splitext(path)[1].lower()
    name = os.path.basename(path)
    if ext == '.docx':
        try:
            import docx  # type: ignore
        except ImportError:
            sys.exit('برای docx بستهٔ python-docx لازم است (pip install python-docx)؛ یا متن را در پروندهٔ txt بدهید.')
        d = docx.Document(path)
        paras = [p.text for p in d.paragraphs]
        for t in d.tables:
            for row in t.rows:
                for c in row.cells:
                    paras.append(c.text)
        return [(name, '\n'.join(paras), False)]
    raw = open(path, encoding='utf-8-sig').read()
    if ext == '.py':
        segs = []
        for node in ast.walk(ast.parse(raw)):
            if isinstance(node, ast.Constant) and isinstance(node.value, str) and re.search('[' + LET + ']', node.value):
                segs.append(('{0}:{1}'.format(name, node.lineno), node.value, False))
        return sorted(segs, key=lambda x: int(x[0].rsplit(':', 1)[1]))
    if ext == '.json':
        segs = []

        def walk(node, key):
            if isinstance(node, dict):
                for k, v in node.items():
                    walk(v, key + '.' + str(k))
            elif isinstance(node, list):
                for i, v in enumerate(node):
                    walk(v, '{0}[{1}]'.format(key, i))
            elif isinstance(node, str) and re.search('[' + LET + ']', node):
                segs.append((name + key, node, False))
        walk(json.loads(raw), '')
        return segs
    return [(name, raw, True)]


def report(label, text, findings, per_code=12, lines=True):
    counts = {k: sum(1 for f in findings if f[1] == k) for k in 'EWC'}
    out = ['== {0}: خطا {1} · هشدار {2} · وارسی {3}'.format(label, counts['E'], counts['W'], counts['C'])]
    shown = {}
    for code, level, s, e, msg, rep in findings:
        shown[code] = shown.get(code, 0) + 1
        if shown[code] > per_code:
            continue
        a = max(0, s - 22)
        ctx = text[a:min(len(text), e + 22)].replace('\n', ' ⏎ ')
        where = 'س{0} '.format(text.count('\n', 0, s) + 1) if lines else ''
        out.append('{0} {1:<11} {2}{3}  ┆ …{4}…'.format(level, code, where, msg, ctx))
    for code, n in shown.items():
        if n > per_code:
            out.append('  … و {0} مورد دیگر از {1}'.format(n - per_code, code))
    return '\n'.join(out), counts


